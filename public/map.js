let bigGrid = [
    [5,1,1,1,8],
    [4,0,0,0,2],
    [4,0,0,0,2],
    [4,0,0,0,2],
    [6,3,3,3,8],
]

function createArray(w,h,fill){
    let array = []
    for(let i = 0; i < h; i++){
        array[i] = []
        for(let j = 0; j < w; j++){
            array[i][j] = fill
        }
    }
    return array
}

function createMap() {
    myMap = createArray(bigGrid.length * 9, bigGrid.length * 9, 0)

    for(let i = 0; i < bigGrid.length; i ++) {
        for(let j = 0; j < bigGrid.length; j++){
            for(let k = 0; k < 9; k++){
                for(let l = 0; l < 9; l++){
                    myMap[k + 9 * i][l + 9 * j] = mapPresets[bigGrid[i][j]][k][l]
                }
            }
        }
    }

    socket.emit("myMap",myMap)
}
